	DIVISIONALVICEPRESIDENT,
	REGIONALMARKETINGMANAGER,
	FRANCHISEOWNERSHIPGROUP,
	LOYALTYLOCATION,
	LOYALTY_ALCOHOLEARNING,
	POSSOFTWAREKEYID
