        IFNULL(TO_VARCHAR(r.closure_date, 'mm/dd/yyyy'),'') as StoreCloseDate,
        '' as GeneralManager,
        '' as RegionalManager,
        '' as DirectorofOperations,
        '' as DivisionalVicePresident,
        '' as RegionalMarketingManager,
