AS 'DECLARE
	  load_dt VARCHAR DEFAULT '''';
	  response_message STRING;
	  counter INTEGER DEFAULT 0;
      trun := ''truncate STG_DEV.JJE.ENTITY'';
     insert_into := ''insert into STG_DEV.JJE.PDQ_''||LOAD_TABLE_NAME||''_RAW
     (source_data,
     LOAD_ID,
     LOAD_DTTM,
     FOLDER_DATE
     )select 
     source_data,
     date(sysdate())::STRING AS LOAD_ID,
     sysdate()::STRING AS LOAD_DTTM,
     ''||load_dt||''::STRING AS FOLDER_DATE
     from STG_DEV.JJE.ENTITY'';

    INPUT_PARAM_EXCEPTION EXCEPTION (-20001,''Either load table name is invalid or invalid combination of load_start_dt and load_end_date'');
    BEGIN 
     
             
                LET res RESULTSET := ( WITH CTE_MY_DATE AS ( SELECT DATEADD(DAY, -SEQ4(), :load_end_date) AS MY_DATE FROM TABLE(GENERATOR(ROWCOUNT=>99999)) )
                                SELECT substr(replace(MY_DATE,''-'',''''),1,8) as my_date  FROM CTE_MY_DATE
                                where substr(my_date,1,10) >= :load_start_date);
                    LET cur CURSOR for res;
                    FOR row_variable IN cur DO
                    EXECUTE IMMEDIATE :trun;
                        load_dt := row_variable.MY_DATE;
                        response_message := (CALL STG_DEV.JJE.proc_copy_into_pdq(:load_dt,:to_date,:LOAD_TABLE_NAME));
                        counter := counter + 1;
                             insert_into := ''insert into STG_DEV.JJE.PDQ_''||LOAD_TABLE_NAME||''_RAW
