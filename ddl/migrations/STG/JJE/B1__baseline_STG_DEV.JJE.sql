     LOAD_ID,
     LOAD_DTTM,
     FOLDER_DATE
     )select 
     source_data,
     date(sysdate())::STRING AS LOAD_ID,
     sysdate()::STRING AS LOAD_DTTM,
     ''||:load_dt||''::STRING AS FOLDER_DATE
     from STG_DEV.JJE.ENTITY'';
                        EXECUTE IMMEDIATE :insert_into;
                    END FOR;  
                    
                    RETURN ''Source files for ''||:counter||'' date/dates loaded successfully for daily incremental load in table ''||:LOAD_TABLE_NAME;
    
    EXCEPTION
      WHEN STATEMENT_ERROR THEN
      RETURN OBJECT_CONSTRUCT(''Error type'', ''STATEMENT_ERROR'',
