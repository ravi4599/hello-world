// Loop through each column
while (columnsResult.next()) {
  const columnName = columnsResult.getColumnValue(1);
  const tableAlias = columnsResult.getColumnValue(2);
  // Compare values between tables based on a common identifier
  const comparisonQuery = `
      INSERT INTO ${tempTableName}
      SELECT t1.${primary_key}, ${columnName}, t1.${columnName}, t2.${columnName}
      FROM ${db1}.${schema1}.${table1} t1
      JOIN ${db2}.${schema2}.${table2} t2 ON t1.${primary_key} = t2.${primary_key}
      WHERE t1.${columnName} IS NULL OR t2.${columnName} IS NULL OR t1.${columnName} != t2.${columnName}
  `;
