      PRIMARY_KEY_VALUE VARCHAR,
      COLUMN_NAME VARCHAR,
      ${table1}_1 varchar,
      ${table2}_2 varchar
  )
`;
snowflake.createStatement({ sqlText: createTableQuery }).execute();
// Get the list of column names from both tables
const columnsQuery = `
SELECT COLUMN_NAME || t1 AS COLUMN_NAME, ${table1} AS TABLE_ALIAS
FROM ${db1}.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = :3 AND TABLE_SCHEMA = :2
UNION ALL
SELECT COLUMN_NAME || t2 AS COLUMN_NAME, ${table2} AS TABLE_ALIAS
FROM ${db2}.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = :6 AND TABLE_SCHEMA = :5
`;
