create view IF NOT EXISTS MO_SOURCE_PARTNER_BV(
	CURRENT_TABLE,
	PARTNER_NM,
	INSPIRE_PARTNER_NM,
	BRAND_ID,
	SOURCE_SYSTEM_NM,
	INSERTING_INTO_TABLE,
	NEW_BRAND_ID,
	NEW_SOURCE_SYSTEM_NM
) as 
SELECT
*
FROM
(
  --Check PartnerName from MEDIA_PARTNER with BRAND_ID and SOURCE_SYSTE_NM
  SELECT DISTINCT
      'MEDIA_PARTNER' as CURRENT_TABLE
      ,p.PARTNER_NM
      ,NULL as INSPIRE_PARTNER_NM
      ,p.BRAND_ID
      ,p.SOURCE_SYSTEM_NM
      ,'MEDIA_CHANNEL_HIERARCHY_REF' as INSERTING_INTO_TABLE
      ,'internal' as NEW_BRAND_ID
      ,ref.SOURCE_SYSTEM_NM as NEW_SOURCE_SYSTEM_NM
  FROM IDS_DEV.MEDIA.MEDIA_PARTNER p
  LEFT JOIN IDS_DEV.MEDIA.MEDIA_CHANNEL_HIERARCHY_REF ref ON remove_special_char(ref.SOURCE_PARTNER_NM) = remove_special_char(p.PARTNER_NM)
  WHERE ref.SOURCE_PARTNER_NM IS NULL
  UNION
  
  --Check SOURCE_PARTNER_NM from MEDIA_CHANNEL_HIERARCHY_REF
  SELECT DISTINCT
      'MEDIA_CHANNEL_HIERARCHY_REF' as CURRENT_TABLE
      ,ref.SOURCE_PARTNER_NM
      ,ref.INSPIRE_PARTNER_NM as INSPIRE_PARTNER_NM
      ,ref.BRAND_ID
      ,ref.SOURCE_SYSTEM_NM
      ,'MEDIA_PARTNER' as INSERTING_INTO_TABLE
      ,p.BRAND_ID as NEW_BRAND_ID
      ,p.SOURCE_SYSTEM_NM as NEW_SOURCE_SYSTEM_NM
  FROM IDS_DEV.MEDIA.MEDIA_CHANNEL_HIERARCHY_REF ref
  LEFT JOIN IDS_DEV.MEDIA.MEDIA_PARTNER p ON remove_special_char(ref.SOURCE_PARTNER_NM) = remove_special_char(p.PARTNER_NM)
  WHERE p.PARTNER_NM IS NULL
) src
ORDER BY src.CURRENT_TABLE DESC,src.PARTNER_NM
;
