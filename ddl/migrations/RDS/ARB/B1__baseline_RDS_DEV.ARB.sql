        S.pickuptime,
        coalesce(H.hits_transaction_transactionShipping,0) / POW(10,6) as shipping,
        coalesce(H.hits_transaction_transactionTax,0) / POW(10,6) as tax,
        NULL as tip, -- tip isn't tracked yet
        coalesce(H.hits_transaction_transactionRevenue,0) / POW(10,6) as value,
        value - tax as subtotal
    FROM session_transaction
    pivot(listagg(customdimensions_value) for customdimensions_index in (3, 1, 5))
    S (UserID, FullVisitorID, VisitNumber, VisitID, Date,dataset_id, visitstarttime, pickuptime, fulfilment, storeNumber)
