        TO_TIME(DATEADD(millisecond,H.hits_time,TO_TIMESTAMP(S.visitstarttime))) AS TIME_UTC,
        TO_TIMESTAMP(S.visitstarttime) AS SESSION_START_TIME_UTC,
        RDS_DEV.IRB.CONVERT_TIMESTAMP_FROM_UTC_TO_TIMEZONE(TO_TIMESTAMP(S.visitstarttime),store.TIMEZONE) AS SESSION_START_TIME_LOCAL,
