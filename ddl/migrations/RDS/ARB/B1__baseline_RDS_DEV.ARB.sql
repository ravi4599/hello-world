CREATE FUNCTION IF NOT EXISTS ARRAY_NOT_CONTAINED("ARRAY1" ARRAY, "ARRAY2" ARRAY)
RETURNS ARRAY
LANGUAGE JAVA
HANDLER = 'ArrayNotContained.perform'
TARGET_PATH = '@DQ_UDFS_STAGE/ArrayNotContained.jar'
AS '
    import java.util.ArrayList;
    import java.util.Arrays;
    import java.util.List;
    import java.util.stream.Stream;
    class ArrayNotContained {
        public static String[] perform(String[] x, String[] y) {
              final List<String> xAsList = new ArrayList<>(Arrays.asList(x));
              final Stream<String> concatDistinct = Stream.concat(Stream.of(x), Stream.of(y)).distinct();
              return concatDistinct.filter(elem -> !xAsList.contains(elem)).toArray(java.lang.String[]::new);
        }
    }
';
