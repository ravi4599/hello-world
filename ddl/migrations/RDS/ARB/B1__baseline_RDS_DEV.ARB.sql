create view IF NOT EXISTS ADDED_PRODUCTS_TO_CART(
	USERID,
	SESSION_START_TIME_UTC,
	SESSION_START_TIME_LOCAL,
	FULLVISITORID,
	VISITID,
	VISITNUMBER,
	EVENTCATEGORY,
	EVENTACTION,
	HITNUMBER,
	PRODUCTNAME,
	PRODUCTPRICE,
	QUANTITY,
	CARTORDER
) as
(
   WITH session_transaction as
   (
      SELECT Distinct
         UserID,
         FullVisitorID,
         VisitNumber,
         VisitID::string as VisitID,
         visitstarttime,
         customdimensions_value
      FROM
         SESSION
      WHERE
         customdimensions_index = 5
   )
,
   hit_transaction as
   (
      SELECT DISTINCT
         FullVisitorID,
         VisitNumber,
         VisitID::string as VisitID,
         hits_hitNumber,
         hits_eventInfo_eventCategory,
         hits_eventInfo_eventAction,
         hits_product_v2ProductName,
         hits_product_productPrice,
         hits_product_productQuantity
      FROM
         HIT
      WHERE
         hits_eventInfo_eventCategory = 'Order'
         AND
         (
            hits_eventInfo_eventAction = 'Quantity Increase'
            OR hits_eventInfo_eventAction = 'Add to Cart'
         )
   )
   SELECT
      distinct
      S.UserId AS UserId,
      to_timestamp(S.VisitStartTime) AS SESSION_START_TIME_UTC,
      RDS_DEV.IRB.CONVERT_TIMESTAMP_FROM_UTC_TO_TIMEZONE(SESSION_START_TIME_UTC, store.TIMEZONE) AS SESSION_START_TIME_LOCAL,
      S.FullVisitorId,
      S.VisitId::string AS VisitId,
      S.VisitNumber,
      H.hits_eventInfo_eventCategory AS EventCategory,
      H.hits_eventInfo_eventAction AS EventAction,
      H.hits_hitNumber AS HitNumber,
      H.hits_product_v2ProductName AS ProductName,
      H.hits_product_productPrice/POW(10,6) AS ProductPrice, -- by default in source hits_product_productPrice is multiplied by 10^6 (e.g., 2.40 would be given as 2400000)
      ifnull(H.hits_product_productQuantity::int, 1) AS Quantity,
      DENSE_RANK() OVER (PARTITION BY S.FullVisitorId, S.VisitId, SESSION_START_TIME_UTC, S.VisitNumber ORDER BY HitNumber) AS CartOrder
   FROM
      session_transaction S
      JOIN
         hit_transaction H
         ON H.VISITID = S.VISITID
         AND H.VISITNUMBER = S.VISITNUMBER
         AND H.FULLVISITORID = S.FULLVISITORID
      LEFT JOIN
         RDS_DEV.IRB.STORE_DIM AS store
         ON store.BRAND_ID = 'arbys'
         AND S.CUSTOMDIMENSIONS_VALUE = store.STORE_KEY::STRING
);
create view IF NOT EXISTS BAG_FINAL_SALES_AMOUNTS(
