HANDLER = 'TimestampAddByInterval.perform'
TARGET_PATH = '@DQ_UDFS_STAGE/TimestampAddByInterval.jar'
AS '
    import java.sql.Timestamp;
    import java.time.LocalDateTime;
    import java.time.ZoneOffset;
    import java.time.temporal.ChronoUnit;
    class TimestampAddByInterval {
            public static Timestamp perform(Timestamp ts, String intervalAsString) {
                if(ts == null) {
                    return new Timestamp(0L);
                }
                String[] intervalArray = intervalAsString.split(" ");
                if (intervalArray.length != 6) throw new RuntimeException("Lenght of interval not valid. Must be 6 digits");
                final LocalDateTime tsLocalDateTime = ts.toLocalDateTime();

                return Timestamp.valueOf(
                    tsLocalDateTime.plus(Integer.parseInt(intervalArray[0]), ChronoUnit.YEARS)
                      .plus(Integer.parseInt(intervalArray[1]), ChronoUnit.MONTHS)
                      .plus(Integer.parseInt(intervalArray[2]), ChronoUnit.DAYS)
                      .plus(Integer.parseInt(intervalArray[3]), ChronoUnit.HOURS)
                      .plus(Integer.parseInt(intervalArray[4]), ChronoUnit.MINUTES)
                      .plus(Integer.parseInt(intervalArray[5]), ChronoUnit.SECONDS));
            }
        }
';
