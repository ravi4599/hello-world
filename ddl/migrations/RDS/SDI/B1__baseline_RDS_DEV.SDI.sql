CREATE FUNCTION IF NOT EXISTS DECIMALNUMBER("SOURCE_DATA" VARCHAR(16777216), "NUMFROM" NUMBER(38,0), "NUMTO" NUMBER(38,0), "LITERAL" NUMBER(38,0))
RETURNS FLOAT
LANGUAGE SQL
AS '
select case substr(source_data,literal,1)
  when ''}'' then -CONCAT(substr(replace(substr(source_data,numfrom,numto),''}'',''0''),1,3),''.'',substr(replace(substr(source_data,numfrom,5),''}'',''0''),4,2))
  when ''J'' then -CONCAT(substr(replace(substr(source_data,numfrom,numto),''J'',''1''),1,3),''.'',substr(replace(substr(source_data,numfrom,numto),''J'',''1''),4,2))
  when ''K'' then -CONCAT(substr(replace(substr(source_data,numfrom,numto),''K'',''2''),1,3),''.'',substr(replace(substr(source_data,numfrom,numto),''K'',''2''),4,2))
  when ''L'' then -CONCAT(substr(replace(substr(source_data,numfrom,numto),''L'',''3''),1,3),''.'',substr(replace(substr(source_data,numfrom,numto),''L'',''3''),4,2))
  when ''M'' then -CONCAT(substr(replace(substr(source_data,numfrom,numto),''M'',''4''),1,3),''.'',substr(replace(substr(source_data,numfrom,numto),''M'',''4''),4,2))
  when ''N'' then -CONCAT(substr(replace(substr(source_data,numfrom,numto),''N'',''5''),1,3),''.'',substr(replace(substr(source_data,numfrom,numto),''N'',''5''),4,2))
  when ''O'' then -CONCAT(substr(replace(substr(source_data,numfrom,numto),''O'',''6''),1,3),''.'',substr(replace(substr(source_data,numfrom,numto),''O'',''6''),4,2))
  when ''P'' then -CONCAT(substr(replace(substr(source_data,numfrom,numto),''P'',''7''),1,3),''.'',substr(replace(substr(source_data,numfrom,numto),''P'',''7''),4,2))
  when ''Q'' then -CONCAT(substr(replace(substr(source_data,numfrom,numto),''Q'',''8''),1,3),''.'',substr(replace(substr(source_data,numfrom,numto),''Q'',''8''),4,2))
  when ''R'' then -CONCAT(substr(replace(substr(source_data,numfrom,numto),''R'',''9''),1,3),''.'',substr(replace(substr(source_data,numfrom,numto),''R'',''9''),4,2))
  ELSE CONCAT(substr(substr(source_data,numfrom,numto),1,3),''.'',substr(substr(source_data,numfrom,numto),4,2))
  end as Dollars_Inp
   
';
CREATE FUNCTION IF NOT EXISTS DECIMALNUMBER2("SOURCE_DATA" VARCHAR(16777216))
RETURNS FLOAT
LANGUAGE SQL
AS '
select case right(source_data,1)
  when ''}'' then -CONCAT(substr(replace(source_data,''}'',''0''),1,3),''.'',substr(replace(source_data,''}'',''0''),4,2))
  when ''J'' then -CONCAT(substr(replace(source_data,''J'',''1''),1,3),''.'',substr(replace(source_data,''J'',''1''),4,2))
  when ''K'' then -CONCAT(substr(replace(source_data,''K'',''2''),1,3),''.'',substr(replace(source_data,''K'',''2''),4,2))
