create view IF NOT EXISTS WEEKLY_SALES(
	BRAND_ID,
	WEEK_START_DATE,
	REST_ID,
	DMA_CODE,
	DMA_NAME,
	SALES_AMT,
	TRANS_CNT
) as
with cte_week
as
	(select  to_varchar(cal_date,'YYYY-MM-DD') cal_date_str
	        ,Fisc_Wk_Start_Date
      From IDH_DEV.D_REF.DATE
     )
select 
	 ord.brand_id brand_id,
	 wk.Fisc_Wk_Start_Date WEEk_Start_Date,
	 ord.rest_id rest_Id,
	 r.dma_code AS dma_code,
	 r.dma_name AS dma_name,
	 sum(source_net_amt) Sales_Amt,
	 count(*) Trans_Cnt 
from  IDH_DEV.D_TRANS.TRANS ORD
left join idh_dev.D_LOC.REST r 
on ord.rest_id = R.rest_id and ord.brand_id = r.brand_id
left join cte_week wk 
on ord.business_date = wk.cal_date_str
group by ord.brand_id,
 ord.rest_id,
 wk.Fisc_Wk_Start_Date,
 r.dma_code,
 r.dma_name
;