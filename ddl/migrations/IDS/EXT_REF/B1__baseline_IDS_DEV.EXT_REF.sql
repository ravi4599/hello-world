  fiscal_last_year.FY_Comp_Trans_Cnt_Day as Fc_Comp_Trans_LY,
  calendar_last_year.AGG_START_DT,
  calendar_last_year.FY_Net_Sales_Day as Cal_Net_Sales_LY,
  calendar_last_year.FY_Net_Trans_Cnt_Day as Cal_Trans_LY,
  calendar_last_year.FY_Comp_Sales_Day as Cal_Comp_Sales_LY,
  calendar_last_year.FY_Comp_Trans_Cnt_Day as Cal_Comp_Trans_LY,
  calendar_two_years.AGG_START_DT,
  calendar_two_years.FY_Net_Sales_Day as Cal_Net_Sales_2Y,
  calendar_two_years.FY_Net_Trans_Cnt_Day as Cal_Trans_2Y,
  calendar_two_years.FY_Comp_Sales_Day as Cal_Comp_Sales_2Y,
  calendar_two_years.FY_Comp_Trans_Cnt_Day as Cal_Comp_Trans_2Y,
  calendar_three_years.AGG_START_DT,
  calendar_three_years.FY_Net_Sales_Day as Cal_Net_Sales_3Y,
  calendar_three_years.FY_Net_Trans_Cnt_Day as Cal_Trans_3Y,
  calendar_three_years.FY_Comp_Sales_Day as Cal_Comp_Sales_3Y,
  calendar_three_years.FY_Comp_Trans_Cnt_Day as Cal_Comp_Trans_3Y
  FROM 
  table(FLASH_SUMMARY_NO_COMP_FISCAL(BUSINESS_DATE)) as fiscal_curr_year
  inner join VW_COMP_CAL_DATE_3YR dt
  on dt.date_id = fiscal_curr_year.business_dt
  left outer join 
  table(FLASH_SUMMARY_NO_COMP_FISCAL(select FISCAL1YRCOMP_DATEID from VW_COMP_CAL_DATE_3YR where date_id = BUSINESS_DATE)) as fiscal_last_year
  on dt.FISCAL1YRCOMP_DATEID = fiscal_last_year.business_dt
  and fiscal_curr_year.store_id = fiscal_last_year.store_id
  and fiscal_curr_year.brand_id = fiscal_last_year.brand_id
  and fiscal_curr_year.AGG_LEVEL = fiscal_last_year.AGG_LEVEL
