  fiscal_curr_year.brand_id ASC, 
  fiscal_curr_year.store_id ASC,
  (case when fiscal_curr_year.AGG_LEVEL = ''DY'' then 1
    when fiscal_curr_year.AGG_LEVEL = ''WTD'' then 2
    when fiscal_curr_year.AGG_LEVEL = ''PTD'' then 3
    when fiscal_curr_year.AGG_LEVEL = ''QTD'' then 4
    when fiscal_curr_year.AGG_LEVEL = ''YTD'' then 5 END) ASC,
  fiscal_last_year.business_dt DESC
  ';
CREATE FUNCTION IF NOT EXISTS FLASH_SUMMARY_NO_COMP_CALENDAR("BUSINESS_DATE" DATE)
RETURNS TABLE ("BRAND_ID" VARCHAR(16777216), "STORE_ID" VARCHAR(16777216), "BUSINESS_DT" DATE, "CY_NET_TRANS_CNT_DAY" NUMBER(38,0), "CY_NET_SALES_DAY" NUMBER(38,0), "CY_COMP_TRANS_CNT_DAY" NUMBER(38,0), "CY_CAL_COMP_SALES_DAY" NUMBER(38,0), "AGG_START_DT" DATE, "AGG_LEVEL" VARCHAR(16777216), "CY_COMP_ELIGIBLE_DAY" VARCHAR(16777216), "DMA_NAME" VARCHAR(16777216), "OWNERSHIP_TYPE" VARCHAR(16777216), "STATE" VARCHAR(16777216), "COUNTRY" VARCHAR(16777216), "L1NAME" VARCHAR(16777216), "L2NAME" VARCHAR(16777216), "L3NAME" VARCHAR(16777216), "L4NAME" VARCHAR(16777216), "L5NAME" VARCHAR(16777216), "OPEN_15P_FLAG" BOOLEAN, "CLOSED_BEFORE_PERIOD_END_FLAG" BOOLEAN, "OPEN_AFTER_HONEYMOON_FLAG" BOOLEAN)
LANGUAGE SQL
AS '

WITH COMP_DATE AS 
(
SELECT  
    BUSINESS_DATE AS calendar_dt -- comparison date
    , opendt.calendar_dt as MAX_OPEN_DT -- ODI-53 maximum open date for which the store will be comp when reporting at BUSINESS_DATE
    , opendthoney.calendar_dt as MAX_HONEY_DT -- ODI-199 maximum open date for which the store will be out of honeymoon period (3 full fiscal periods) at BUSINESS_DATE
FROM "IDS_DEV"."DATASTORE"."DATE_DIM" as opendt
INNER JOIN "IDS_DEV"."DATASTORE"."DATE_DIM" as busdt
on
    iff (opendt.FISCAL_PERIOD_START_DT = opendt.CALENDAR_DT
        , (opendt.FISCAL_PERIOD_NBR+15)%12
        , (opendt.FISCAL_PERIOD_NBR+16)%12
    ) = busdt.FISCAL_PERIOD_NBR
and iff (opendt.FISCAL_PERIOD_START_DT = opendt.CALENDAR_DT
        , opendt.FISCAL_YEAR_NBR + trunc((opendt.FISCAL_PERIOD_NBR+15)/12)
        , opendt.FISCAL_YEAR_NBR + trunc((opendt.FISCAL_PERIOD_NBR+16)/12)
    ) = busdt.FISCAL_YEAR_NBR
INNER JOIN "IDS_DEV"."DATASTORE"."DATE_DIM" as opendthoney --ODI-199
on
    (opendthoney.FISCAL_PERIOD_NBR +
            iff(opendthoney.FISCAL_PERIOD_START_DT = opendthoney.CALENDAR_DT, 3, 4)
    ) % 12 = busdt.FISCAL_PERIOD_NBR
and 
    opendthoney.FISCAL_YEAR_NBR + trunc(
        (opendthoney.FISCAL_PERIOD_NBR +
                iff(opendthoney.FISCAL_PERIOD_START_DT = opendthoney.CALENDAR_DT, 3, 4)
        ) / 12
    ) = busdt.FISCAL_YEAR_NBR
where opendt.calendar_dt = opendt.FISCAL_PERIOD_START_DT
and opendthoney.calendar_dt = opendthoney.FISCAL_PERIOD_START_DT
and busdt.calendar_dt = BUSINESS_DATE
)
