  table(FLASH_SUMMARY_NO_COMP_FISCAL(select CALENDAR2YRCOMP_DATEID from VW_COMP_CAL_DATE_3YR where date_id = BUSINESS_DATE)) as calendar_two_years
  on dt.CALENDAR2YRCOMP_DATEID = calendar_two_years.business_dt
