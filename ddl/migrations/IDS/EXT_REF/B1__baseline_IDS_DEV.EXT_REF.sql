CREATE FUNCTION IF NOT EXISTS DAILY_SALES("BUSINESS_DATE" DATE)
RETURNS TABLE ("BRAND_ID" VARCHAR(16777216), "STORE_ID" VARCHAR(16777216), "BUSINESS_DT" DATE, "CY_NET_SALES_DAY" NUMBER(38,0), "CY_NET_TRANS_CNT_DAY" NUMBER(38,0), "CY_CAL_COMP_SALES_DAY" NUMBER(38,0), "CY_CAL_TRANS_CNT_DAY" NUMBER(38,0), "CY_COMP_ELIGIBLE_DAY" VARCHAR(16777216), "DMA_NAME" VARCHAR(16777216), "OWNERSHIP_TYPE" VARCHAR(16777216), "STATE" VARCHAR(16777216), "COUNTRY" VARCHAR(16777216))
LANGUAGE SQL
AS '

SELECT
    CASE    WHEN UPPER(dfsf.BRAND_ID) = ''ARG'' THEN ''Arbys'' 
            WHEN UPPER(dfsf.BRAND_ID) = ''BWW'' THEN ''BWW''
            WHEN UPPER(dfsf.BRAND_ID) = ''SDI'' THEN ''Sonic''
            ELSE ''UNKNOWN''
            END AS BRAND_ID
    , dfsf.STORE_ID
    , dfsf.BUSINESS_DT
    , SUM(dfsf.NET_SALES_AMT) OVER(PARTITION BY dfsf.BRAND_ID, dfsf.STORE_ID, dfsf.BUSINESS_DT) AS CY_Net_Sales_Day
    , SUM(dfsf.TRANSACTION_CNT) OVER(PARTITION BY dfsf.BRAND_ID, dfsf.STORE_ID, dfsf.BUSINESS_DT) AS CY_Net_Trans_Cnt_Day
    , SUM(dfsf.NET_SALES_AMT) OVER(PARTITION BY dfsf.BRAND_ID, dfsf.STORE_ID, dfsf.BUSINESS_DT) AS CY_Cal_Comp_Sales_Day
    , SUM(dfsf.TRANSACTION_CNT) OVER(PARTITION BY dfsf.BRAND_ID, dfsf.STORE_ID, dfsf.BUSINESS_DT) AS CY_Cal_Trans_Cnt_Day  
    , ''Y'' AS CY_Comp_Eligible_Day
    , IFNULL(st.DMA_NAME, ''UNKNOWN'') AS DMA_NAME
    , IFNULL(st.OWNERSHIP_TYPE, ''UNKNOWN'') AS OWNERSHIP_TYPE
    , IFNULL(st.STATE, ''UNKNOWN'') AS STATE
    , IFNULL(st.COUNTRY, ''UNKNOWN'') AS COUNTRY
FROM 
    IDS_DEV.DATASTORE.DAILY_FLASH_SALES_FACT dfsf
LEFT OUTER JOIN
    IDH_DEV.SHARED.STORE_V st
ON  dfsf.STORE_ID = st.STORE_ID
AND dfsf.BRAND_ID = st.BRAND_ID
INNER JOIN
    IDH_DEV.SHARED.DATE_DIM_V d
ON  dfsf.BUSINESS_DT = d.CALENDAR_DT
INNER JOIN
    IDH_DEV.SHARED.DATE_DIM_V d1c
ON  d1c.CALENDAR_DT = d.CALENDAR_COMPARABLE_DT
INNER JOIN
    IDH_DEV.SHARED.DATE_DIM_V d2c
ON  d2c.CALENDAR_DT = d1c.CALENDAR_COMPARABLE_DT
INNER JOIN
    IDH_DEV.SHARED.DATE_DIM_V d3c
ON  d3c.CALENDAR_DT = d2c.CALENDAR_COMPARABLE_DT
WHERE
    dfsf.BRAND_ID = ''ARG''
AND dfsf.SOURCE_SYSTEM_NM = ''RTI''
AND NOT (dfsf.BRAND_ID = ''ARG'' AND dfsf.SOURCE_SYSTEM_NM <> ''RTI'')
AND IFNULL(st.COUNTRY, ''US'') = ''US''
AND IFNULL(st.IS_CURRENT, 1) = 1 /*Replace IFNULL when st will be filled*/

';
