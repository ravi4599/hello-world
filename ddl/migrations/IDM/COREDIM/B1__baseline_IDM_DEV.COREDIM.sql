LANGUAGE SCALA
RUNTIME_VERSION = '2.12'
PACKAGES = ('com.snowflake:snowpark:1.4.0')
HANDLER = 'PopulateChannelDim.run'
TARGET_PATH = '@IDM_DEV.CSO.STORED_PROCEDURES/PopulateChannelDim.jar'
