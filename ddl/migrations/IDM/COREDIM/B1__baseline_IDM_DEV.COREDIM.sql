AS '
object PopulateChannelDim {
  def run(session: com.snowflake.snowpark.Session): String = {
    import com.snowflake.snowpark.{Column, DataFrame, MergeResult}
    import com.snowflake.snowpark.functions._

    def toCol(colName: String): DataFrame => Column = df => df(colName)
    def toColConst(f: () => Column): DataFrame => Column = _ => f()

    /** Clone the dataframe 5 times projecting the columns with the format prefix+iteration+name
      * @maxDepth number indicating how many levels of parentship need to be cloned
      * @baseDf source DataFrame that will be joined with itself
      * @param tableType (MDMOrderChannelHierarchy,MDMFulfillmentChannel)
      * @param prefix Alias for the table at each iteration
      * @return All the DataFrames as collection
      */
    def cloneWithPrefixes(
        maxDepth: Int,
        baseDf: DataFrame,
        tableType: String,
        prefix: String
    ): Seq[DataFrame] =
      (1 to maxDepth).reverse
        .map(num =>
          baseDf
            .clone()
            .select(
              col(s"MDM${tableType}HierarchyId")
                .as(s"${prefix + num}_MDM${tableType}HierarchyId"),
              col(s"PARENT${tableType}HierarchyId")
                .as(s"${prefix + num}_PARENT${tableType}HierarchyId"),
              col(s"${tableType}HierarchyName")
                .as(s"${prefix + num}_${tableType}HierarchyName"),
              col("Source")
                .as(s"${prefix + num}_Source")
            )
        )
        .toList

    /** Get the history dataframe, with prefix as table alias and Table Type (Product,Offer).
      * Trigger the clone with prefix and then recursively make the enrichment as following
      * Prefix5 join (
      *    Prefix4 join (
      *        Prefix3 join (
      *            Prefix2 join Prefix1
      *        )
      *    )
      * )
      * @param baseDf source DataFrame that will be joined with itself
      * @param tableType (MDMOrderChannelHierarchy,MDMFulfillmentChannel)
      * @param prefix Alias for the table at each iteration
      * @return Joined and Flatten Dataframe
      */
    def recursiveEnrichAndTakeNameFromPrevious(
        maxDepth: Int,
        baseDf: DataFrame,
        tableType: String,
        prefix: String
    ): DataFrame = {

      def flatAndEnrich(
          accumulator: DataFrame,
          enrich: Seq[DataFrame],
          actualIteration: Int
      ): DataFrame = {
        enrich match {
          case Nil => accumulator
          case next :: others =>
            val prevRes = flatAndEnrich(next, others, actualIteration - 1)
            accumulator.join(
              prevRes,
              accumulator(
                s"${prefix + actualIteration}_Parent${tableType}HierarchyId"
              ).equal_to(
                prevRes(
                  s"${prefix + (actualIteration - 1)}_MDM${tableType}HierarchyId"
                )
              ),
              "left"
            )
        }
      }
      val generatedDataframesWithAlias =
        cloneWithPrefixes(maxDepth, baseDf, tableType, prefix)

      flatAndEnrich(
        generatedDataframesWithAlias.head,
        generatedDataframesWithAlias.tail,
        generatedDataframesWithAlias.size
      )
    }

    def cleanupDataframe(
            dataFrame: DataFrame,
            keyMapping: Map[String, DataFrame => Column]
    ) = {
      // cleaning null PKs and make null all empty strings or null as string
      dataFrame
        .where(
          keyMapping.map(_._2(dataFrame).is_not_null).reduce(_ and _)
        )
        .select(
          dataFrame.schema.fields.map(field =>
            iff(
              lower(dataFrame(field.name)).in(Seq(lit(""), lit("null"))),
              lit(null),
              dataFrame(field.name)
            ).as(field.name)
          )
        )
    }

    val keyMapping = Map(
      "CHANNEL_ID" -> toCol("ChannelId"),
      "BRAND_ID" -> toCol("BrandId")
    )

    val mapping: Map[String, DataFrame => Column] = keyMapping ++ Map(
      "ORDER_CHANNEL_NM" -> toCol("OrderChannelName"),
      "FULFILLMENT_CHANNEL_NM" -> toCol("FulfillmentChannelName"),
      "ORDER_CHANNEL_HIERARCHY_L3_NM" -> toCol(
        "OrderChannelHierarchyName_L3"
      ),
      "ORDER_CHANNEL_HIERARCHY_L2_NM" -> toCol(
        "OrderChannelHierarchyName_L2"
      ),
      "ORDER_CHANNEL_HIERARCHY_L1_NM" -> toCol(
        "OrderChannelHierarchyName_L1"
      ),
      "FULFILLMENT_CHANNEL_HIERARCHY_L3_NM" -> toCol(
        "FulfillmentChannelHierarchyName_L3"
      ),
      "FULFILLMENT_CHANNEL_HIERARCHY_L2_NM" -> toCol(
        "FulfillmentChannelHierarchyName_L2"
      ),
      "FULFILLMENT_CHANNEL_HIERARCHY_L1_NM" -> toCol(
        "FulfillmentChannelHierarchyName_L1"
      ),
      "SOURCE_SYSTEM_NM" -> toCol("Source").andThen(col =>
        coalesce(col, lit("cdm"))
      ),
      "HIERARCHY_SOURCE_SYSTEM_NM" -> toCol("HIERARCHYSOURCE"),
      "CDM_LOAD_DT" -> toCol("CDMLoadDate"),
      "CDM_UPDATE_DT" -> toCol("CDMUpdateDate"),
      "LOAD_ID" ->
        toColConst(() =>
          sqlExpr(
            "cast(to_varchar(SYSDATE(),''yyyymmddhh24missFF3'') as NUMBER(38,0))"
          )
        ),
      "LOAD_DTTM" -> toColConst(() => sysdate()),
      "UPDATE_ID" ->
        toColConst(() =>
          sqlExpr(
            "cast(to_varchar(SYSDATE(),''yyyymmddhh24missFF3'') as NUMBER(38,0))"
          )
        ),
      "UPDATE_DTTM" -> toColConst(() => sysdate())
    )

    val updates: Map[String, DataFrame => Column] =
      mapping - ("CHANNEL_ID", "SOURCE_SYSTEM_NM", "BRAND_ID", "LOAD_ID", "LOAD_DTTM")
    val whenMatchMapping: Map[String, DataFrame => Column] =
      mapping - ("UPDATE_ID", "UPDATE_DTTM", "LOAD_ID", "LOAD_DTTM")
    val whenMatchedCondition: (DataFrame, DataFrame) => Column =
      (target, source) =>
        {
          whenMatchMapping map { case (targetKey, sourceMapping) =>
            coalesce(target(targetKey), lit("")) not_equal coalesce(
              sourceMapping(source),
              lit("")
            )
          }
        } reduce (_ or _)

    val dfTranChannelPlr = session.table("CDMSYNC_DEV.IRB.TRAN_CHANNEL_PLR_CHANNEL_DIM_STREAM")
    val dfTranChannelHierPlr =
      session.table("CDMSYNC_DEV.IRB.TRAN_ORDERCHANNEL_HIERARCHY_PLR_CHANNEL_DIM_STREAM")
    val dfTranFulFillChannelPlr =
      session.table("CDMSYNC_DEV.IRB.TRAN_FULFILLMENTCHANNEL_HIERARCHY_PLR_CHANNEL_DIM_STREAM")

    val target = session.table("CHANNEL_DIM")

    val och321 = recursiveEnrichAndTakeNameFromPrevious(
      3,
      dfTranChannelHierPlr,
      "OrderChannel",
      "och"
    )
    val ffh321 = recursiveEnrichAndTakeNameFromPrevious(
      3,
      dfTranFulFillChannelPlr,
      "FulfillmentChannel",
      "ffh"
    )

    val sourceRaw = dfTranChannelPlr
      .join(
        och321,
        dfTranChannelPlr("MDMOrderChannelHierarchyId") equal_to och321(
          "OCH3_MDMOrderChannelHierarchyId"
        ),
        "left"
      )
      .join(
        ffh321,
        dfTranChannelPlr("MDMFulfillmentChannelHierarchyId") equal_to ffh321(
          "FFH3_MDMFulfillmentChannelHierarchyId"
        ),
        "left"
      )

    val sourceDf = cleanupDataframe(
      sourceRaw.select(
        dfTranChannelPlr("ChannelId"),
        dfTranChannelPlr("OrderChannelName"),
        dfTranChannelPlr("FulfillmentChannelName"),
        och321("OCH3_ORDERCHANNELHIERARCHYNAME").as(
          "OrderChannelHierarchyName_L3"
        ),
        och321("OCH2_ORDERCHANNELHIERARCHYNAME").as(
          "OrderChannelHierarchyName_L2"
        ),
        och321("OCH1_ORDERCHANNELHIERARCHYNAME").as(
          "OrderChannelHierarchyName_L1"
        ),
        ffh321("FFH3_FULFILLMENTCHANNELHIERARCHYNAME").as(
          "FulfillmentChannelHierarchyName_L3"
        ),
        ffh321("FFH2_FULFILLMENTCHANNELHIERARCHYNAME").as(
          "FulfillmentChannelHierarchyName_L2"
        ),
        ffh321("FFH1_FULFILLMENTCHANNELHIERARCHYNAME").as(
          "FulfillmentChannelHierarchyName_L1"
        ),
        dfTranChannelPlr("Source"),
        och321("OCH3_SOURCE").as("HierarchySource"),
        dfTranChannelPlr("BrandId"),
        dfTranChannelPlr("CDMLoadDate"),
        dfTranChannelPlr("CDMUpdateDate")
      ),
      keyMapping
    )

    val result: MergeResult = target
      .merge(
        sourceDf,
        keyMapping.map(key =>
          target(key._1) equal_to key._2(sourceDf)
        ) reduce (_ and _)
      )
      .whenMatched(whenMatchedCondition(target, sourceDf))
      .update(updates.mapValues(_(sourceDf)))
      .whenNotMatched
      .insert(mapping.mapValues(_(sourceDf)))
      .collect()
    s"Rows Inserted ${result.rowsInserted} - Rows Updated ${result.rowsUpdated}"
  }
}
